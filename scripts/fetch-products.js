#!/usr/bin/env node
// One-off script — run from project root: node scripts/fetch-products.js
// Fetches the available Internetmarke products and prints a starter products.yaml.
// Verify the PRODUCTS_URL below against the DP API docs / Postman collection.

require('dotenv').config();

const PRODUCTS_URL = 'https://api-eu.dhl.com/post/de/shipping/im/v1/app/products';
const AUTH_URL = 'https://api-eu.dhl.com/post/de/shipping/im/v1/user';

async function main() {
  const credentials = Buffer.from(`${process.env.DP_API_KEY}:${process.env.DP_API_SECRET}`).toString('base64');

  const authRes = await fetch(AUTH_URL, {
    method: 'POST',
    headers: { 'Authorization': `Basic ${credentials}`, 'Content-Type': 'application/json' },
    body: JSON.stringify({ username: process.env.DP_PORTOKASSE_USER, password: process.env.DP_PORTOKASSE_PASS }),
  });
  if (!authRes.ok) {
    console.error('Auth failed:', await authRes.text());
    process.exit(1);
  }
  const auth = await authRes.json();
  const token = auth.access_token;

  const prodRes = await fetch(PRODUCTS_URL, {
    headers: { 'Authorization': `BearerToken ${token}` },
  });
  if (!prodRes.ok) {
    console.error(`Products fetch failed (${prodRes.status}):`, await prodRes.text());
    process.exit(1);
  }
  const products = await prodRes.json();

  // Adjust this mapping based on the actual response shape
  console.log('# Deutsche Post Internetmarke product catalog');
  console.log('# Generated by scripts/fetch-products.js — verify prices before use');
  console.log('');
  console.log('products:');
  const list = Array.isArray(products) ? products : (products.products || products.items || []);
  list.forEach(p => {
    console.log(`  - id: "${p.id ?? p.productCode ?? p.code}"`);
    console.log(`    name: "${p.name ?? p.description}"`);
    console.log(`    price_cents: ${p.price ?? p.priceInCents ?? p.cost ?? '# TODO: fill in'}`);
    console.log('');
  });
}

main().catch(err => { console.error(err); process.exit(1); });
